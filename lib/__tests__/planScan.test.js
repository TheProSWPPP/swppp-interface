import zlib from "zlib";
import { execFileSync } from "child_process";
import { PDFDocument, StandardFonts } from "pdf-lib";
import { encodeGrayPng, cutTiles, parsePgm, quoteInText, verifyEvidence, choosePages, pageTexts, pageTiles, scanPlanSet } from "../planScan.js";

const hasGs = (() => { try { execFileSync("gs", ["--version"]); return true; } catch { return false; } })();

function readPngGray(png) {
  expect(png.subarray(0, 8)).toEqual(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
  const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
  let offset = 8; const idat = [];
  while (offset < png.length) {
    const len = png.readUInt32BE(offset); const type = png.toString("ascii", offset + 4, offset + 8);
    if (typeof zlib.crc32 === "function") expect(png.readUInt32BE(offset + 8 + len)).toBe(zlib.crc32(png.subarray(offset + 4, offset + 8 + len)) >>> 0);
    if (type === "IDAT") idat.push(png.subarray(offset + 8, offset + 8 + len));
    offset += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const gray = Buffer.alloc(width * height);
  for (let y = 0; y < height; y++) raw.copy(gray, y * width, y * (width + 1) + 1, (y + 1) * (width + 1));
  return { width, height, gray };
}

describe("plan scan image tiles", () => {
  it("encodes a grayscale PNG that decodes back to the same pixels", () => {
    const gray = Buffer.from([0, 50, 100, 150, 200, 250]);
    const back = readPngGray(encodeGrayPng(gray, 3, 2));
    expect([back.width, back.height]).toEqual([3, 2]);
    expect(back.gray).toEqual(gray);
  });

  it("cuts a D-size sheet into overlapping tiles that cover every pixel", () => {
    const width = 4800, height = 3200;
    const data = Buffer.alloc(width * height);
    for (let i = 0; i < data.length; i++) data[i] = i % 251;
    const tiles = cutTiles({ width, height, data });
    expect(tiles).toHaveLength(6);
    expect(tiles.every((t) => t.rows === 2 && t.cols === 3)).toBe(true);
    const first = readPngGray(tiles[0].png);
    expect(first.width).toBeGreaterThan(1600);
    expect(first.gray[0]).toBe(data[0]);
    const last = readPngGray(tiles[5].png);
    expect(last.gray[last.gray.length - 1]).toBe(data[data.length - 1]);
  });

  it("keeps a letter-size page whole", () => {
    expect(cutTiles({ width: 1500, height: 1200, data: Buffer.alloc(1500 * 1200) })).toHaveLength(1);
  });

  it("reads Ghostscript's image header including its comment line", () => {
    const buf = Buffer.concat([Buffer.from("P5\n# Image generated by GPL Ghostscript (device=pgmraw)\n4 2\n255\n", "latin1"), Buffer.alloc(8, 7)]);
    const img = parsePgm(buf);
    expect([img.width, img.height, img.data.length]).toEqual([4, 2, 8]);
  });
});

describe("plan scan evidence", () => {
  const page = "GENERAL NOTES\nTOTAL DISTURBED AREA\nSEE SHEET C-2\n4.75 ± acres\nOWNER / DEVELOPER\n7B Building & Development";

  it("accepts a quote whose label and value sit on different lines", () => {
    expect(quoteInText("TOTAL DISTURBED AREA 4.75 ± acres", page)).toBe(true);
  });

  it("rejects a quote whose number is not on the page", () => {
    expect(quoteInText("TOTAL DISTURBED AREA 3.07 acres", page)).toBe(false);
  });

  it("marks quotes as found in text, missing from text, or image only", () => {
    const evidence = {
      estimatedDisturbedArea: { page: 1, quote: "TOTAL DISTURBED AREA 4.75 ± acres" },
      ownerName: { page: 1, quote: "OWNER: Someone Else LLC 555" },
      soilComposition: { page: 2, quote: "Clay loam" },
    };
    verifyEvidence(evidence, [page, ""]);
    expect(evidence.estimatedDisturbedArea.verified).toBe("text");
    expect(evidence.ownerName.verified).toBe("not_in_text");
    expect(evidence.soilComposition.verified).toBe("image_only");
  });

  it("keeps chosen pages in range, unique, capped and ascending", () => {
    expect(choosePages([12, 1, 12, 99, "3", 0], 20)).toEqual([1, 3, 12]);
    expect(choosePages(null, 3)).toEqual([1, 2, 3]);
    expect(choosePages([...Array(20).keys()].map((i) => i + 1), 30)).toHaveLength(8);
  });
});

async function makePlanPdf(file) {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const sheets = [["C-0.0 COVER SHEET", "OWNER: City of Testville"], ["C-6.0 EROSION CONTROL PLAN", "TOTAL DISTURBED AREA 1.25 AC"]];
  for (const [title, line] of sheets) {
    const p = doc.addPage([2592, 1728]); // 36 x 24 in
    p.drawText(title, { x: 100, y: 1600, size: 40, font });
    p.drawText(line, { x: 100, y: 1500, size: 30, font });
  }
  fs.writeFileSync(file, await doc.save());
}

describe.skipIf(!hasGs)("plan scan with Ghostscript", () => {
  it("reads each page's text and zooms a D-size sheet into tiles", async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "planscan-test-"));
    try {
      const file = path.join(dir, "plans.pdf");
      await makePlanPdf(file);
      const texts = await pageTexts(file, dir);
      expect(texts).toHaveLength(2);
      expect(texts[1]).toContain("TOTAL DISTURBED AREA 1.25 AC");
      const { tiles, dpi } = await pageTiles(file, 2);
      expect(dpi).toBe(133);
      expect(tiles).toHaveLength(6);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }, 60000);

  it("stops text extraction when a sheet draws hatching with huge amounts of glyphs", async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "planscan-test-"));
    try {
      const doc = await PDFDocument.create();
      const font = await doc.embedFont(StandardFonts.Helvetica);
      doc.addPage([612, 792]).drawText("COVER SHEET", { x: 50, y: 700, size: 20, font });
      for (let n = 0; n < 3; n++) {
        const p = doc.addPage([2592, 1728]);
        for (let y = 20; y < 1700; y += 6) p.drawText(".".repeat(400), { x: 10, y, size: 6, font });
      }
      const file = path.join(dir, "hatch.pdf");
      fs.writeFileSync(file, await doc.save());
      const texts = await pageTexts(file, dir, { maxTotalBytes: 200 * 1024 });
      expect(texts.capped).toBe(true);
      expect(texts[0]).toContain("COVER SHEET");
      expect(texts.length).toBeLessThan(4);
      expect(fs.readdirSync(dir)).toEqual(["hatch.pdf"]);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }, 60000);

  it("runs both passes and verifies the quoted area against the PDF text", async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "planscan-test-"));
    try {
      const file = path.join(dir, "plans.pdf");
      await makePlanPdf(file);
      const calls = [];
      const replies = [
        { sheets: [{ page: 1, sheet: "C-0.0", title: "COVER SHEET", kind: "cover" }, { page: 2, sheet: "C-6.0", title: "EROSION CONTROL PLAN", kind: "erosion_control" }], readClosely: [2, 1] },
        { estimatedDisturbedArea: { value: "1.25", method: "explicit_label", details: "Printed on C-6.0" }, summary: "Test", evidence: { estimatedDisturbedArea: { page: 2, sheet: "C-6.0", quote: "TOTAL DISTURBED AREA 1.25 AC", confidence: "high" } } },
      ];
      const fetchImpl = async (url, init) => {
        const body = JSON.parse(init.body);
        calls.push({ url, body });
        const reply = replies[calls.length - 1];
        return { ok: true, status: 200, json: async () => ({ candidates: [{ content: { parts: [{ text: JSON.stringify(reply) }] } }], usageMetadata: { promptTokenCount: 1000, candidatesTokenCount: 100 } }) };
      };
      const data = await scanPlanSet(file, { apiKey: "test", basePrompt: "Extract.\nReturn ONLY valid JSON, no markdown formatting.", tmpDir: dir, fetchImpl });
      expect(calls).toHaveLength(2);
      expect(calls[0].url).toContain("gemini-4-argon");
      const tileParts = calls[1].body.contents[0].parts.filter((p) => p.inline_data?.mime_type === "image/png");
      expect(tileParts.length).toBe(12);
      expect(tileParts.every((p) => p.mediaResolution.level === "MEDIA_RESOLUTION_ULTRA_HIGH")).toBe(true);
      expect(data.evidence.estimatedDisturbedArea.verified).toBe("text");
      expect(data.pagesReadClosely).toEqual([1, 2]);
      expect(data.sheetIndex[1].sheet).toBe("C-6.0");
      expect(data._usage.pdfPages).toBe(2);
      expect(fs.readdirSync(dir)).toEqual(["plans.pdf"]);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }, 60000);

  it("accepts a reply wrapped in a one-item array", async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "planscan-test-"));
    try {
      const file = path.join(dir, "plans.pdf");
      await makePlanPdf(file);
      const replies = [
        [{ sheets: [{ page: 1, sheet: "C-0.0", title: "COVER SHEET", kind: "cover" }], readClosely: [1] }],
        [{ estimatedDisturbedArea: { value: "1.82", method: "explicit_label", details: "Printed" }, evidence: {} }],
      ];
      let n = 0;
      const fetchImpl = async () => ({ ok: true, status: 200, json: async () => ({ candidates: [{ content: { parts: [{ text: JSON.stringify(replies[n++]) }] } }], usageMetadata: {} }) });
      const data = await scanPlanSet(file, { apiKey: "test", basePrompt: "Extract.", tmpDir: dir, fetchImpl });
      expect(data.estimatedDisturbedArea.value).toBe("1.82");
      expect(data.sheetIndex[0].sheet).toBe("C-0.0");
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }, 60000);
});

export function getTemplateColor(templateIdOrName?: string): string {
  const name = getTemplateName(templateIdOrName);
  if (!name) return "bg-slate-50 text-slate-700 border-slate-200";
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = name.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % colors.length;
  return colors[index];
}

export function isAutomatedDocument(docName: string): boolean {
  const automated = ["Job Cover Letter", "Construction Site Notice"];
  return automated.includes(docName);
}
